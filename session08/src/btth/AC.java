package btth;

public class AC {
    int temp;

    public AC(int temp) {
        this.temp = temp;
    }

    public int getTemp() {
        return temp;
    }

    public void setTemp(int temp) {
        this.temp = temp;
    }

    public void changeTemp(int newTemp) {
        this.temp = newTemp;
    }
}
